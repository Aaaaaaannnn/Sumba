import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {dirname,resolve} from 'node:path';
import vm from 'node:vm';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const get=p=>readFileSync(resolve(root,p),'utf8');
let n=0;const check=(expr,message)=>{assert.ok(expr,message);n++};
const js=get('public/real/real.js'),cfg=get('public/real/config.js'),html=get('public/real/index.html'),headers=get('public/real/_headers');
new vm.Script(js);new vm.Script(cfg);
check(html.includes('<title>SUMBA | Acesso seguro</title>'),'SUMBA title');
check(html.includes('name="sumba-version" content="0.24.0"'),'version');
check(cfg.includes('oauth:Object.freeze({google:true})'),'Google OAuth button configured; provider still requires external validation');
check(js.includes("location.protocol==='https:'"),'HTTPS only');
check(js.includes("c.routes?.some?.(r=>r.origin===location.origin&&r.path===location.pathname)") && !cfg.includes('origin:"https://sumba.stivenluanda04.workers.dev"'), 'auth only on allowlisted origin and path');
check(js.includes("shouldCreateUser:false"),'OTP cannot create a new account');
check(js.includes("type:otpTypes[mode]"),'server-side token verification');
check(js.includes("resetPasswordForEmail(identifier"),'server-side recovery');
check(js.includes("client.auth.updateUser({email},{emailRedirectTo:redirect})"),'email change request');
check(js.includes("client.auth.getUser()"),'server-validated session');
check(js.includes('inputmode="numeric"'),'numeric keyboard in OTP');
check(js.includes('class="otp-digits"'),'six digit visual slots');
check(js.includes("Array.from({length:6}"),'six digit boxes count');
check(js.includes("mode==='reset'||mode==='otp'||mode==='login'"),'email login uses OTP first');
check(js.includes("mode!=='password'"),'password remains an optional fallback');
check(js.includes("client.auth.verifyOtp(options)"),'OTP verified by Supabase Auth');
check(js.includes("client.auth.getUserIdentities()"),'identities from auth server');
check(js.includes("linkIdentity({provider,options})"),'linking is requested from auth server');
check(js.includes("pendingKey='sumba-auth-otp-v2'"),'pending request metadata key');
check(js.includes("sessionStorage.setItem(pendingKey"),'reload persistence');
check(!js.includes('sessionStorage.setItem(pendingKey,token'),'no OTP token persistence');
check(js.includes("client.auth.signOut({scope:'global'})"),'global sign-out after reset');
check(js.includes("['buyer','producer','company'].includes(s('role'))"),'no self-admin role');
check(headers.includes("frame-ancestors 'none'"),'clickjacking protection');
check(headers.includes('Cache-Control: no-store'),'no caching');
for(const name of ['confirm-signup','magic-link','recovery','reauthentication']){const t=get('supabase/auth-templates/'+name+'.html');check(t.includes('SUMBA'),name+' brand');check(t.includes('{{ .Token }}'),name+' code placeholder')}
for(const name of ['invite','email-change']){const t=get('supabase/auth-templates/'+name+'.html');check(t.includes('{{ .ConfirmationURL }}'),name+' confirmed link')}
for(const name of ['password-changed'])check(get('supabase/auth-templates/'+name+'.html').includes('SUMBA'),name+' branded');
check(get('wrangler.auth.jsonc').includes('"directory": "./public/real"'),'isolated deployment');
check(get('public/index.html')===get('index.html'),'demo copies');
const script=get('scripts/configure-sumba-auth.mjs');check(script.includes("const REF='asxyjhaujsowmdrpkcqc'"),'dedicated Supabase project');
check(script.includes("const SITE='https://zunga-auth.stivenluanda04.workers.dev/'"),'technical origin preserved');
check(script.includes("mailer_templates_email_change_content"),'email change template');
check(script.includes("mailer_templates_invite_content"),'invitation template');
check(script.includes("mode==='status'"),'readiness check command');
check(!/\bservice_role\s*[:=]/.test(js) && /publishableKey:"sb_publishable_/.test(cfg) && !/publishableKey:"sb_secret_/.test(cfg),'no privileged browser key');
console.log('SUMBA auth contract '+n+' checks passed. No live sending/authentication tested.');
